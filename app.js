  function officeNewsFor(entries, butlerName, seed) {
    const level = entries.map(entry => Number(entry.obsession) || 0).reduce((a, b) => Math.max(a, b), 0);
    const pool = level >= 60 ? OFFICE_NEWS.max : level >= 40 ? OFFICE_NEWS.high : level >= 20 ? OFFICE_NEWS.mid : null;
    if (!pool) return "";
    return pool[seed % pool.length].replaceAll("{butler}", butlerName || "담당");
  }

  function analyzeDiarySource(entry) {
    const sourceText = storedText(entry?.sourceText).trim();
    if (!sourceText) return null;
    try {
      return window.OVERBUTLER_MESSAGE_INTERPRETER?.analyzeUserMessage(sourceText) || null;
    } catch { return null; }
  }

  function dominantDiaryMood(entries) {
    const order = ["tired", "sad", "low", "angry", "worried", "happy"];
    const moods = entries.map(entry => analyzeDiarySource(entry)?.mood || entry.mood).filter(Boolean);
    return order.find(item => moods.includes(item)) || "neutral";
  }

  // 일기 재료는 사용자가 직접 남긴 원문을 다시 해석한 결과가 최우선이다.
  // 원문이 없거나 해석되지 않는 구버전 기록만 저장된 activities, deed 순으로 사용한다.
  function diaryActionLabels(entries) {
    const labels = [];
    entries.forEach(entry => {
      const sourceActivities = analyzeDiarySource(entry)?.activities || [];
      const list = sourceActivities.length
        ? sourceActivities
        : Array.isArray(entry.activities) && entry.activities.length
          ? entry.activities
          : [entry.deed || entry.todos?.[0]].filter(Boolean);
      list.forEach(label => { if (label && !labels.includes(label)) labels.push(label); });
    });
    return labels;
  }

  function diaryReflection(character, entries, ownerName = entries.at(-1)?.ownerName || ownerDisplayName()) {
    const key = normalizeCharacter(character);
    const voice = DIARY_VOICE[key] || DIARY_VOICE.ai;
    const labels = diaryActionLabels(entries);
    const phrases = labels.map(actionPhrase);
    const owner = ownerName || ownerDisplayName();
    const seedSource = `${entries[0]?.date || ""}|${key}|${labels.join("|")}`;
    const seed = seedSource.split("").reduce((total, value) => total + value.charCodeAt(0), 0);
    const moodKey = dominantDiaryMood(entries);
    const sentences = [];

    if (phrases.length) {
      sentences.push(phrases[0].known
        ? speak(voice.open(owner, phrases[0].verb), key)
        : speak(`오늘 ${owner}의 기록에는 ${phrases[0].verb}${withParticle(phrases[0].noun, "이", "가").slice(phrases[0].noun.length)} 남았다`, key));
    }
    const rest = phrases.slice(1);
    const moodLead = voice.moodLead?.[moodKey];
    if (rest.length) {
      const nouns = rest.slice(0, 2).map(item => item.noun);
      const tail = rest.length > 2 ? `${nouns.join("랑 ")} 같은 것` : nouns.join("랑 ");
      // 감정과 남은 행동을 한 문장으로 엮는다: "꽤 힘들었다고 했는데 씻기까지 했다냥."
      sentences.push(moodLead
        ? speak(`${moodLead} ${voice.alsoLead(tail)}`, key)
        : speak(voice.also(tail), key));
    } else if (moodKey !== "neutral" || !phrases.length) {
      sentences.push(speak(voice.moodAlone[moodKey] || voice.moodAlone.neutral, key));
    }
    // 사무국 소식은 마무리 인사 앞에 넣는다. 인사로 끝나야 일기가 닫힌다.
    const news = officeNewsFor(entries, entries.at(-1)?.butlerName, seed);
    if (news) sentences.push(news);
    sentences.push(voice.close[seed % voice.close.length]);
    const separator = key === "ai" ? "\n" : " ";
    return sentences.map(sentence => /[.!?…🌙🐾✨]$/.test(sentence) ? sentence : `${sentence}.`).join(separator);
  }

  function backfillDiaryReflections() {
    const groups = new Map();
    let changed = false;
    state.diary.forEach(entry => {
      const character = normalizeCharacter(entry.butler?.character || entry.character);
      const key = `${entry.date || "날짜 미상"}::${character}::${entry.butler?.name || entry.butlerName || ""}`;
      if (!groups.has(key)) groups.set(key, []);
      const entries = groups.get(key);
      entries.push(entry);
      if (!entry.reflection) {
        entry.reflection = diaryReflection(character, entries, entry.ownerName || entries.at(-1)?.ownerName || ownerDisplayName());
        entry.reflectionVersion = 1;
        changed = true;
      }
    });
    return changed;
  }

  function unlockPastDiaryEntries() {
    state.diary.forEach(entry => {
      if (nonNegativeInteger(entry.diaryRevealVersion) > 0 && entry.date < today()) entry.diaryRevealed = true;
    });
  }

